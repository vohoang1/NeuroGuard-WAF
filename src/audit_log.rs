#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::AttackType;

    fn make_report() -> ThreatReport {
        ThreatReport::new(AttackType::SqlInjection, 0.97, "UNION SELECT", Some(0))
    }

    #[test]
    fn log_event_does_not_panic_on_block() {
        log_event(
            &make_report(),
            "POST",
            "/api/login",
            "10.0.0.1",
            "curl/8.0",
            0.0,
            &Decision::Block,
            "00000000-0000-0000-0000-000000000000",
        );
    }

    #[test]
    fn log_event_does_not_panic_on_challenge() {
        log_event(
            &make_report(),
            "GET",
            "/search",
            "192.168.1.1",
            "Mozilla/5.0",
            0.5,
            &Decision::Challenge,
            "00000000-0000-0000-0000-000000000000",
        );
    }

    #[test]
    fn audit_event_serialises_to_valid_json() {
        let report = make_report();
        let event = AuditEvent {
            timestamp: 1_700_000_000_000,
            tenant_id: "00000000-0000-0000-0000-000000000000",
            correlation_id: "req-123".to_string(),
            source_ip: "1.2.3.4",
            method: "POST",
            uri: "/login",
            attack_type: report.attack_type.as_str(),
            confidence: report.confidence,
            rule_id: report.rule_id,
            action: "BLOCK",
            user_agent: "Mozilla/5.0",
            country_code: "UNKNOWN",
            ai_score: 0.97,
        };
        let json = serde_json::to_string(&event).expect("serialise failed");
        assert!(json.contains("\"attack_type\":\"SQL_INJECTION\""));
        assert!(json.contains("\"action\":\"BLOCK\""));
        assert!(json.contains("\"rule_id\":0"));
    }

    #[test]
    fn path_truncation_in_log_event() {
        // A 600-byte path must not cause a panic or produce a 600-byte path field.
        let long_path = "A".repeat(600);
        log_event(
            &make_report(),
            "GET",
            &long_path,
            "1.2.3.4",
            "Mozilla/5.0",
            0.0,
            &Decision::Block,
            "00000000-0000-0000-0000-000000000000",
        );
        // No assertion needed beyond "does not panic"; the truncation logic
        // is tested here by exercising the slice operation.
    }
}
